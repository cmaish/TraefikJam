// Builds js/levels-data.js — the campaign levels, pre-generated so every
// device gets the exact same, verified-solvable puzzles.
// Usage: node tools/build-levels.mjs
import { writeFileSync } from 'node:fs';
import { generate, analyze } from '../js/generator.js';
import { levelParams, CAMPAIGN_LEVELS } from '../js/worlds.js';

const handmade = [
  // 1: one car, just tap it!
  { w: 3, h: 4, vehicles: [{ x: 1, y: 1, len: 2, dir: 0 }], obstacles: [], pets: [] },
  // 2: two cars, one in the way
  { w: 3, h: 4, vehicles: [{ x: 1, y: 2, len: 2, dir: 0 }, { x: 0, y: 1, len: 2, dir: 1 }], obstacles: [], pets: [] },
  // 3: three cars
  {
    w: 4, h: 4,
    vehicles: [{ x: 1, y: 2, len: 2, dir: 0 }, { x: 0, y: 1, len: 2, dir: 3 }, { x: 2, y: 1, len: 2, dir: 2 }],
    obstacles: [], pets: [],
  },
];

const out = [];
let stats = [];
for (let n = 1; n <= CAMPAIGN_LEVELS; n++) {
  let lvl;
  if (n <= handmade.length) {
    lvl = handmade[n - 1];
  } else {
    const p = levelParams(n);
    lvl = generate(p, n * 7919 + 13);
  }
  const info = analyze(lvl);
  if (!info.solvable) throw new Error('Level ' + n + ' unsolvable');
  out.push({
    w: lvl.w, h: lvl.h,
    v: lvl.vehicles.map((v) => [v.x, v.y, v.len, v.dir]),
    o: lvl.obstacles.map((o) => [o.x, o.y]),
    p: lvl.pets.map((o) => [o.x, o.y]),
  });
  stats.push(`${n}:${lvl.w}x${lvl.h} v${lvl.vehicles.length} d${info.depth} f${info.freeStart}`);
}
const body = '// Generated by tools/build-levels.mjs — do not edit by hand.\nexport const LEVELS = ' +
  JSON.stringify(out).replace(/\},\{/g, '},\n{') + ';\n';
writeFileSync(new URL('../js/levels-data.js', import.meta.url), body);
console.log(stats.join('\n'));
